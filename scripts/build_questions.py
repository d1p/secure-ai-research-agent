def main() -> None:
    missing = []
    for slug, questions in Q.items():
        out = FIXTURES / slug / "questions.json"
        if not out.parent.exists():
            missing.append(slug)
            continue
        out.write_text(
            json.dumps(questions, indent=2, ensure_ascii=False) + "\n",
            encoding="utf-8",
        )
        print(f"wrote {out.relative_to(ROOT)} ({len(questions)} questions)")
    for slug in ("paywall-cookie", "challenge-bot"):
        meta_path = FIXTURES / slug / "meta.json"
        if meta_path.exists():
            meta = json.loads(meta_path.read_text())
            meta["expected_needs_human"] = True
            meta_path.write_text(
                json.dumps(meta, indent=2, sort_keys=True) + "\n", encoding="utf-8"
            )
    if missing:
        raise SystemExit(f"missing fixtures: {missing}")


if __name__ == "__main__":
    main()
